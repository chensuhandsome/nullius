def _curl_download(url: str, out_path: Path, timeout: int = 120) -> tuple[int, str]:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    cmd = ["curl", "-L", "--fail", "--silent", "--show-error", "--max-time", str(timeout), "-o", str(out_path), url]
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, check=False)
    return proc.returncode, proc.stdout.decode("utf-8", errors="replace")


def _allowed_command(command: str) -> tuple[bool, str, list[str]]:
    """Parse and validate *command*.

    Returns ``(allowed, reason, parsed_parts)``.  When *allowed* is True the
    caller must use *parsed_parts* to run the command with ``shell=False`` so
    that shell metacharacters in the original string are never interpreted by a
    shell.  This eliminates the entire class of injection vectors (`;`, `&&`,
    `$(`, process-substitution, etc.).
    """
    banned_exes = {"sudo", "rm", "mkfs", "mount", "umount", "shutdown", "reboot"}
    try:
        parts = shlex.split(command, posix=True)
    except Exception:
        return False, "command is not parseable via shlex", []
    if not parts:
        return False, "empty command", []
    # Check every token for banned executable names (basename match).
    for part in parts:
        part_lower = part.strip().lower()
        basename = part_lower.rsplit("/", 1)[-1]
        if basename in banned_exes:
            return False, f"contains banned executable: {part!r}", []
    exe = parts[0]
    exe_lower = exe.lower()
    allow = {
        "python3",
        "python",
        "julia",
        "bash",
        "sh",
        "make",
        "latexmk",
        "pdflatex",
        "xelatex",
        "lualatex",
        "bibtex",
        "biber",
        "rg",
        "grep",
        "sed",
        "awk",
        "cat",
        "head",
        "tail",
        "ls",
        "find",
        "git",
        "curl",
        "wget",
        "tar",
        "unzip",
        "gzip",
        "gunzip",
        "mkdir",
        "touch",
    }
    if not exe.startswith("./") and exe_lower not in allow:
        return False, f"executable not in allowlist: {exe!r}", []
    # bash/sh with -c (or any combined flag containing 'c', e.g. -lc, -ec, --norc -c)
    # executes an arbitrary shell string — not allowed.
    if exe_lower in ("bash", "sh"):
        for _arg in parts[1:]:
            if _arg == "--":
                break  # end of options
            # Match any single-dash flag string containing 'c' (e.g. -c, -lc, -ec, -xc).
            if re.match(r"^-[a-zA-Z]*c[a-zA-Z]*$", _arg):
                return False, "bash/sh -c is not allowed; use a script file instead", []
    # python/python3 with -c executes an arbitrary code string; members can derive
    # run_dir at runtime (Path.cwd().parents[...]) even without literal path strings
    # in their args, so the pre-exec path scan cannot protect against it.
    if exe_lower in ("python3", "python"):
        for _arg in parts[1:]:
            if _arg == "--":
                break
            if re.match(r"^-[a-zA-Z]*c[a-zA-Z]*$", _arg):
                return False, "python -c is not allowed; use a script file instead", []
    # julia -e/-E/--eval/--print similarly allows arbitrary inline code execution.
    if exe_lower == "julia":
        for _arg in parts[1:]:
            if _arg == "--":
                break
            if _arg in ("-e", "-E", "--eval", "--print"):
                return False, "julia -e/-E is not allowed; use a script file instead", []
    # find -exec/-execdir/-ok/-okdir spawn arbitrary subprocesses as a second-order
    # executor and can discover cross-member paths at runtime without embedding
    # the literal run_dir string in argv.
    if exe_lower == "find":
        for _arg in parts[1:]:
            if _arg in ("-exec", "-execdir", "-ok", "-okdir"):
                return False, "find -exec/-execdir is not allowed; use a script instead", []
    # awk/gawk/nawk programs with system(), popen(), or |& allow arbitrary shell
    # execution from within the awk program — same second-order risk as find -exec.
    # Use regex to tolerate whitespace between the function name and '(' since awk
    # allows `system ("cmd")` as well as `system("cmd")`.
    if exe_lower in ("awk", "gawk", "nawk"):
        for _arg in parts[1:]:
            if _arg.startswith("-"):
                continue
            if _AWK_EXEC_RE.search(_arg) or "|&" in _arg:
                return False, "awk programs with system()/popen() are not allowed", []
    return True, "", parts


_SECRET_ENV_RE = re.compile(
    r"(?i)(api[_\-]?key|secret[_\-]?key|auth[_\-]?token|access[_\-]?token|password|credential)",
)
_AWK_EXEC_RE = re.compile(r"system\s*\(|popen\s*\(")
_ARG_TRAVERSAL_RE = re.compile(r"(?:(?:^|[^\w.])\.\.(?:[^\w.]|$))")


def _sanitize_env(env: dict[str, str]) -> dict[str, str]:
    """Return env with secret-bearing variables removed.

    Prevents member-requested subprocesses from exfiltrating API keys or other
    secrets that may be present in the parent environment.
    """
    return {k: v for k, v in env.items() if not _SECRET_ENV_RE.search(k)}


def _run_shell(parts: list[str], cwd: Path, timeout: int, *, episode: object | None = None, operation_index: int = 0) -> tuple[int, bytes]:
    """Run *parts* as a subprocess with shell=False (no shell interpolation)."""
    pending = runtime_capture_observation._member_prepare_process(episode, f"command[{operation_index}]", parts, [], cwd=cwd) if episode is not None else None
    proc = subprocess.Popen(
        parts,
        cwd=str(cwd),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        env=_sanitize_env(dict(os.environ)),
    )
    if episode is not None:
        runtime_capture_observation._member_bind_process(episode, pending, proc)
    try:
        output, _ = proc.communicate(timeout=timeout)
    except BaseException:
        proc.kill(); proc.communicate(); raise
    if episode is not None:
        runtime_capture_observation._member_finish_process(episode, pending, proc, output)
    return proc.returncode, output


def _run_runner(
    runner_kind: str,
    runner: Path,
    system: Path,
    prompt: Path,
    out: Path,
    model: str,
    tools: str,
    output_format: str,
    *,
    runner_max_retries: int | None = None,
    runner_sleep_secs: int | None = None,
    api_base_url: str = "",
    api_key_env: str = "",
    reasoning_effort: str = "",
    invocation: dict[str, Any] | None = None,
    episode: object | None = None,
    stage: str = "",
) -> int:
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd: list[str] = ["bash", str(runner)]
    supports_retry_flags = False
    if runner_kind in ("claude", "codex") and (runner_max_retries is not None or runner_sleep_secs is not None):
        try:
            supports_retry_flags = "--max-retries" in runner.read_text(encoding="utf-8", errors="replace")
        except Exception:
            supports_retry_flags = False
    if supports_retry_flags:
        if runner_max_retries is not None:
            cmd += ["--max-retries", str(int(runner_max_retries))]
        if runner_sleep_secs is not None:
            cmd += ["--sleep-secs", str(int(runner_sleep_secs))]
    if runner_kind in ("claude", "codex"):
        if model.strip():
            cmd += ["--model", model.strip()]
        if runner_kind == "claude":
            cmd += ["--tools", tools if tools != "" else '""']
        if runner_kind == "codex" and reasoning_effort.strip():
            cmd += ["--reasoning-effort", reasoning_effort.strip()]
        cmd += ["--system-prompt-file", str(system), "--prompt-file", str(prompt), "--out", str(out)]
    else:
        if model.strip():
            cmd += ["--model", model.strip()]
        cmd += ["--output-format", output_format.strip() or "text"]
        cmd += ["--prompt-file", str(prompt), "--out", str(out)]
    # Append API configurability args only to runners that advertise that interface.
    if runner_kind != "codex" and api_base_url:
        cmd += ["--api-base-url", api_base_url]
    if runner_kind != "codex" and api_key_env:
        cmd += ["--api-key-env", api_key_env]
    before = {str(p): sha256_file(p) for p in (system, prompt, runner)}
    out.unlink(missing_ok=True)
    pending = runtime_capture_observation._member_prepare_process(episode, stage, cmd, [system, prompt, runner], output=out) if episode is not None else None
    proc = subprocess.Popen(cmd)
    if episode is not None:
        runtime_capture_observation._member_bind_process(episode, pending, proc)
    proc.wait()
    if episode is not None:
        runtime_capture_observation._member_finish_process(episode, pending, proc)
    if invocation is not None:
        invocation.update(argv=cmd, exit_code=proc.returncode, input_sha256={"system": before[str(system)], "prompt": before[str(prompt)], "runner": before[str(runner)]},
                          inputs_unchanged=all(p.is_file() and sha256_file(p) == before[str(p)] for p in (system, prompt, runner)))
    return proc.returncode


def _run_runner_once(
    runner_kind: str,
    runner: Path,
    system: Path,
    prompt: Path,
    out: Path,
    model: str,
    tools: str,
    output_format: str,
    *,
    fast_retry_max: int = 2,
    fast_retry_sleep: int = 1,
    api_base_url: str = "",
    api_key_env: str = "",
    reasoning_effort: str = "",
    invocation: dict[str, Any] | None = None,
    episode: object | None = None,
    stage: str = "",
) -> tuple[int, str]:
    m = (model or "").strip()
    use_fast = runner_kind == "claude" and bool(m)
    code = _run_runner(
        runner_kind=runner_kind,
        runner=runner,
        system=system,
        prompt=prompt,
        out=out,
        model=m,
        tools=tools,
        output_format=output_format,
        invocation=invocation,
        episode=episode,
        stage=stage,
        runner_max_retries=(fast_retry_max if use_fast else None),
        runner_sleep_secs=(fast_retry_sleep if use_fast else None),
        api_base_url=api_base_url,
        api_key_env=api_key_env,
        reasoning_effort=reasoning_effort,
    )
    return code, m


def _build_prompt_for_runner(runner_kind: str, system: Path, user_prompt: str, out_path: Path) -> None:
    if runner_kind in ("claude", "codex"):
        _write_text(out_path, user_prompt)
        return
    # Gemini runner is prompt-only; prepend system prompt deterministically.
    sys_txt = _read_text(system)
    combined = sys_txt.rstrip() + "\n\n" + user_prompt.lstrip()
    _write_text(out_path, combined)


def _format_snippet(text: str, limit: int) -> str:
    if limit < 0 or len(text) > limit:
        raise ValueError("unavailable: complete proxy material exceeds configured visibility budget; no truncation")
    return text


def _parse_requests(obj: Any) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    if not isinstance(obj, dict):
        raise ValueError("requests JSON must be an object")
    req = obj.get("requests", obj)
    if not isinstance(req, dict):
        raise ValueError("requests JSON must be an object (or contain 'requests' object)")
    files = req.get("files_read", [])
    writes = req.get("files_written", [])
    cmds = req.get("commands_run", [])
    net = req.get("network_queries", [])
    if files is None:
        files = []
    if not isinstance(writes, list) or not all(isinstance(x, dict) and isinstance(x.get("path"), str) and isinstance(x.get("content"), str) and isinstance(x.get("purpose"), str) for x in writes):
        raise ValueError("files_written must contain typed path/content/purpose strings")
    if cmds is None:
        cmds = []
    if net is None:
        net = []
    if not isinstance(files, list) or not all(isinstance(x, dict) for x in files):
        raise ValueError("files_read must be a list of objects")
    if not isinstance(cmds, list) or not all(isinstance(x, dict) for x in cmds):
        raise ValueError("commands_run must be a list of objects")
    if not isinstance(net, list) or not all(isinstance(x, dict) for x in net):
        raise ValueError("network_queries must be a list of objects")
    return files, writes, cmds, net


def _extract_convention_mappings(report_text: str) -> list[dict[str, Any]]:
    # Optional: allow a fenced JSON block to populate evidence.convention_mappings.
    # Expected forms:
    # ```json
    # {"convention_mappings":[...]}
    # ```
    m = re.search(r"```json\s*(\{.*?\})\s*```", report_text, flags=re.DOTALL | re.IGNORECASE)
    if not m:
        return []
    try:
        obj = json.loads(m.group(1))
    except Exception:
        return []
    if isinstance(obj, dict) and isinstance(obj.get("convention_mappings"), list):
        out = [x for x in obj["convention_mappings"] if isinstance(x, dict)]
        return out
    return []


def main() -> int:
    args = _parse_args()

    member_id = str(args.member_id).strip()
    tag = str(args.tag).strip()
    mode = str(args.mode).strip()
    if not re.fullmatch(r"[A-Za-z0-9._-]+", tag) or tag == "." or ".." in tag:
        raise SystemExit(f"ERROR: tag must be one safe path segment using only [A-Za-z0-9._-], not '.' and no '..': {tag}")
    if re.fullmatch(r"(?:run_)?[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}", tag):
        raise SystemExit("ERROR: tag looks like a machine-generated UUID; use a meaningful project-local run_id")
    safe_tag = tag

    project_root = args.project_root.resolve()
    workspace_root = args.workspace_root.resolve()
    packet = args.packet.resolve()
    system = args.system.resolve()
    runner = args.runner.resolve()
    run_dir = args.run_dir.resolve()
    member_run_dir = (run_dir / member_id / ("episode-" + uuid.uuid4().hex)).resolve()
    out_report = args.out_report.resolve()
    out_evidence = args.out_evidence.resolve()

    if not packet.is_file():
        print(f"ERROR: packet not found: {packet}", file=sys.stderr)
        return 2
    if not system.is_file():
        print(f"ERROR: system prompt not found: {system}", file=sys.stderr)
        return 2
    if not runner.is_file():
        print(f"ERROR: runner not found: {runner}", file=sys.stderr)
        return 2
    if not workspace_root.is_dir():
        print(f"ERROR: workspace root not found: {workspace_root}", file=sys.stderr)
        return 2

    evidence = new_member_evidence(member_id=member_id, mode=mode, project_root=project_root)
    env = evidence.get("environment")
    if isinstance(env, dict):
        env["runner_kind"] = args.runner_kind
        env["requested_model"] = str(args.model or "").strip()

    # packet_only: one-shot report (no extra evidence).
    if mode == "packet_only":
        prompt_path = member_run_dir / f"{safe_tag}_prompt.txt"
        _build_prompt_for_runner(args.runner_kind, system, _read_text(packet), prompt_path)
        code, model_used = _run_runner_once(
            runner_kind=args.runner_kind,
            runner=runner,
            system=system,
            prompt=prompt_path,
            out=out_report,
            model=args.model,
            tools=args.tools,
            output_format=args.output_format,
            api_base_url=args.api_base_url,
            api_key_env=args.api_key_env,
            reasoning_effort=args.reasoning_effort,
        )
        if code != 0:
            print(f"ERROR: runner failed (exit {code})", file=sys.stderr)
            return 2
        if isinstance(env, dict):
            env["model_used"] = model_used or "(runner default)"
        if out_report.is_file():
            log_output_produced(evidence, _safe_relpath(out_report, project_root), sha256_file(out_report), "member report")
        finalize_member_evidence(evidence)
        save_evidence(out_evidence, evidence)
        # Validate schema (should pass deterministically).
        issues = validate_member_evidence_schema(load_evidence(out_evidence))
        if any(x.level == "ERROR" for x in issues):
            print("ERROR: wrote invalid evidence.json (packet_only)", file=sys.stderr)
            for it in issues:
                print(f"{it.level}: {it.message}", file=sys.stderr)
            return 2
        return 0

    # Archive the complete original material actually passed to both invocations.
    member_run_dir.mkdir(parents=True, exist_ok=True)
    originals = member_run_dir / "originals"
    originals.mkdir(parents=True, exist_ok=True)
    for name, source in (("packet.txt", packet), ("system.txt", system), ("runner.txt", runner)):
        target = originals / name
        target.write_bytes(source.read_bytes())
        log_output_produced(evidence, _safe_relpath(target, project_root), sha256_file(target), f"original {name}")
    packet, system = originals / "packet.txt", originals / "system.txt"
    evidence["original_transport"] = {"version": 1, "packet": artifact_ref(packet, project_root),
                                      "runner": artifact_ref(originals / "runner.txt", project_root), "stages": {}}
    episode = runtime_capture_observation._begin_member_episode(project_root, member_id, [packet, system, originals / "runner.txt"])
    save_evidence(out_evidence, evidence)
    # full_access: requests -> execute -> final report.

    # Initialise audit interceptor whenever workspace isolation is enabled (workspace_id set).
    # This covers both REVIEW_ACCESS_MODE=full_access (workspace_id always provided) and
    # explicit --tool-access=full runs.
    _audit_interceptor: AuditInterceptor | None = None
    if getattr(args, "workspace_id", ""):
        _audit_log_path = run_dir / f"{member_id}_audit.jsonl"
        _audit_interceptor = AuditInterceptor(_audit_log_path, args.workspace_id)
        if isinstance(env, dict):
            env["workspace_id"] = args.workspace_id
            env["tool_access"] = getattr(args, "tool_access", "restricted")

    packet_txt = _read_text(packet)
    req_user_prompt = (
        "MODE: REQUESTS_ONLY\n"
        f"Member: {member_id}\n"
        f"Tag: {tag}\n"
        "\n"
        "You are in full_access mode, but you do NOT have direct tools. Instead, you must output a SINGLE JSON object\n"
        "describing what you want the leader proxy to do. The proxy will execute it, log evidence, and return results.\n"
        "\n"
        "Output contract (STRICT): output JSON only, no prose, no Markdown.\n"
        "JSON schema (minimal):\n"
        "{\n"
        '  "files_written": [{"path": "...", "content": "complete original UTF-8 source", "purpose": "..."}],\n'
        '  "files_read": [{"path": "...", "anchor_or_line": "...", "purpose": "..."}],\n'
        '  "commands_run": [{"command": "...", "cwd": ".", "purpose": "...", "timeout_secs": 600, "input_files": ["raw-input-path"], "expected_outputs": ["..."]}],\n'
        '  "network_queries": [{"query_or_url": "https://...", "justification": "...", "downloaded_to": "references/..."}]\n'
        "}\n"
        "\n"
        f"Limits: files_read<=%d, files_written<=%d, commands_run<=%d, network_queries<=%d.\n"
        "Important constraints:\n"
        "- Do not request executor reports, adjudications, logs, scratch or workspaces from this or any prior run; only your declared output prefix is accessible.\n"
        f"- Prefer producing an independent reproduction script under artifacts/runs/{safe_tag}/research_team/{member_id}/independent/ and at least one output file,\n"
        "  and list those output paths in expected_outputs. Use files_written for your complete source; writes run before reads/commands.\n"
        "- Writes must be inside your independent/ prefix. Commands are literal argv: no pipes, redirection, substitutions or inline -c.\n"
        "\n"
        "Team packet follows.\n"
        "----\n"
        % (args.max_files, args.max_writes, args.max_commands, args.max_network)
    ) + packet_txt

    req_prompt_path = member_run_dir / f"{safe_tag}_requests_prompt.txt"
    _build_prompt_for_runner(args.runner_kind, system, req_user_prompt, req_prompt_path)
    req_out_path = member_run_dir / f"{safe_tag}_requests_out.txt"

    # Save secret env vars before the first runner call so they can be temporarily
    # restored for the final runner call after the proxy stage.
    _saved_secrets: dict[str, str] = {k: v for k, v in os.environ.items() if _SECRET_ENV_RE.search(k)}
    # Also capture the explicitly-named API key var (e.g. --api-key-env AUTH),
    # even if its name does not match _SECRET_ENV_RE.
    _api_key_env_name = getattr(args, "api_key_env", "")
    if _api_key_env_name and _api_key_env_name in os.environ and _api_key_env_name not in _saved_secrets:
        _saved_secrets[_api_key_env_name] = os.environ[_api_key_env_name]

    request_invocation: dict[str, Any] = {}
    code, model_used = _run_runner_once(
        invocation=request_invocation,
        episode=episode,
        stage="requests",
        runner_kind=args.runner_kind,
        runner=runner,
        system=system,
        prompt=req_prompt_path,
        out=req_out_path,
        model=args.model,
        tools=args.tools,
        output_format=args.output_format,
        api_base_url=args.api_base_url,
        api_key_env=args.api_key_env,
        reasoning_effort=args.reasoning_effort,
    )
    record_original_stage(evidence, "requests", request_invocation, system, req_prompt_path, req_out_path, project_root)
    save_evidence(out_evidence, evidence)
    if code != 0:
        print(f"ERROR: runner failed in requests stage (exit {code})", file=sys.stderr)
        return 2
    if isinstance(env, dict):
        env["model_used"] = model_used or "(runner default)"

    # Pop secret env vars so proxy-executed subprocesses cannot exfiltrate them via
    # /proc/<ppid>/environ on Linux.  They are restored below for the final runner call.
    for _k in list(_saved_secrets):
        os.environ.pop(_k, None)

    # Parse requests.
    try:
        req_obj = _extract_json_anywhere(_read_text(req_out_path))
        files_req, writes_req, cmds_req, net_req = _parse_requests(req_obj)
    except Exception as e:
        print("ERROR: failed to parse member requests JSON", file=sys.stderr)
        print(f"  {e}", file=sys.stderr)
        return 2

    pending = []
    for name, requests, limit in (("files_written", writes_req, args.max_writes), ("files_read", files_req, args.max_files), ("commands_run", cmds_req, args.max_commands), ("network_queries", net_req, args.max_network)):
        if limit < 0 or len(requests) > limit:
            pending.extend({"operation": name, "request_index": index, "status": "pending", "reason": "configured operation budget exceeded"} for index in range(len(requests)))
    if pending:
        evidence["original_transport"]["pending_operations"] = pending
        save_evidence(out_evidence, evidence)
        print("ERROR: complete operation requests exceed configured budget; no truncation", file=sys.stderr)
        return 2

    response_lines: list[str] = []
    response_lines.append(f"# Full-access proxy results — {member_id}")
    response_lines.append("")
    response_lines.append(f"- Tag: `{tag}`")
    response_lines.append(f"- Workspace: `{workspace_root}`")
    response_lines.append("")

    # Materialize only exact member-authored source bytes, before reads/commands.
    evidence["original_transport"]["construction_refs"] = []
    if writes_req:
        response_lines.append("## Files Written")
        prefix = f"artifacts/runs/{safe_tag}/research_team/{member_id}/independent/"
        for i, request in enumerate(writes_req):
            try:
                resolved = _resolve_under(workspace_root, request["path"])
                rel = logical_project_relpath(resolved, workspace_root, project_root)
                if not rel.startswith(prefix) or _is_forbidden_path(member_id, safe_tag, rel):
                    raise ValueError("source write is outside own independent prefix")
                data = request["content"].encode("utf-8")
                destination = (project_root / rel).resolve()
                if (not destination.is_relative_to(project_root) or not destination.relative_to(project_root).as_posix().startswith(prefix)):
                    raise ValueError("project source destination is outside own independent prefix")
                if destination.exists() and (not destination.is_file() or destination.read_bytes() != data):
                    raise ValueError("existing project source differs; refusing overwrite")
                resolved.parent.mkdir(parents=True, exist_ok=True)
                created = not resolved.exists()
                if created:
                    with resolved.open("xb") as file: file.write(data)
                elif not resolved.is_file() or resolved.read_bytes() != data:
                    raise ValueError("existing original source differs; refusing overwrite")
                if workspace_root != project_root:
                    sync_workspace_path(resolved, workspace_root, project_root)
                snapshot = originals / f"source_write_{i}.txt"
                snapshot.write_bytes(data)
                log_output_produced(evidence, _safe_relpath(snapshot, project_root), sha256_bytes(data), "complete original model source write")
                log_output_produced(evidence, rel, sha256_bytes(data), request["purpose"])
                evidence["original_transport"]["construction_refs"].append({
                    "kind": "model_source_write", "request_index": i, "path": rel,
                    "sha256": sha256_bytes(data), "size_bytes": len(data), "created": created,
                    "origin_stage": "requests", "source_ref": artifact_ref(req_out_path, project_root),
                    "raw_input_ref": artifact_ref(snapshot, project_root), "purpose": request["purpose"]})
                runtime_capture_observation._member_files(episode, f"source_write[{i}]", [snapshot, resolved, destination], {"created": created})
                if _audit_interceptor is not None:
                    _audit_interceptor.record("file_write", rel, request["content"])
                response_lines.append(f"- files_written[{i}]: `{rel}` (sha256={sha256_bytes(data)}, bytes={len(data)}, created={created})")
            except (OSError, ValueError, UnicodeError) as error:
                response_lines.append(f"- files_written[{i}]: (denied/unavailable) {error}")
        response_lines.append("")
        save_evidence(out_evidence, evidence)

    # Execute file reads.
    if files_req:
        response_lines.append("## Files Read")
        for i, fr in enumerate(files_req):
            path_s = str(fr.get("path", "")).strip()
            anchor = str(fr.get("anchor_or_line", "")).strip()
            purpose = str(fr.get("purpose", "")).strip()
            if not path_s:
                response_lines.append(f"- files_read[{i}]: (skipped) missing path")
                continue
            try:
                resolved = _resolve_under(workspace_root, path_s)
                rel = logical_project_relpath(resolved, workspace_root, project_root)
                if _is_forbidden_path(member_id, safe_tag, rel):
                    response_lines.append(f"- files_read[{i}]: (denied) forbidden path: `{rel}`")
                    continue
                data = resolved.read_bytes()
                txt = data.decode("utf-8")
                raw_read = originals / f"file_read_{i}.txt"
                raw_read.write_bytes(data)
                log_output_produced(evidence, _safe_relpath(raw_read, project_root), sha256_bytes(data), "complete original proxy file read")
                log_file_read(evidence, rel, anchor, purpose)
                evidence["files_read"][-1].update(sha256=sha256_bytes(data), size_bytes=len(data),
                    raw_input_ref=artifact_ref(raw_read, project_root), request_index=i,
                    requested_path=path_s, visible_chars=len(txt))
                runtime_capture_observation._member_files(episode, f"file_read[{i}]", [raw_read, resolved])
                if _audit_interceptor is not None:
                    _tc = _audit_interceptor.record("file_read", rel, txt)
                    _items = evidence.get("files_read", [])
                    if _items and isinstance(_items[-1], dict):
                        _items[-1]["tc_id"] = _tc
                snippet = _format_snippet(txt, args.max_file_chars)
                response_lines.append(f"### files_read[{i}] `{rel}`")
                if purpose:
                    response_lines.append(f"- Purpose: {purpose}")
                if anchor:
                    response_lines.append(f"- Anchor: {anchor}")
                response_lines.append("")
                response_lines.append("```text")
                response_lines.append(snippet.rstrip())
                response_lines.append("```")
                response_lines.append("")
            except Exception as e:
                evidence["original_transport"].setdefault("pending_operations", []).append({"operation":"files_read", "request_index":i, "status":"unavailable", "reason":str(e)})
                response_lines.append(f"- files_read[{i}]: (error) {path_s!r}: {e}")
        response_lines.append("")

    # Execute network queries (URL fetch only).
    if net_req:
        response_lines.append("## Network Queries / Fetches")
        for i, nq in enumerate(net_req):
            url = str(nq.get("query_or_url", nq.get("url", ""))).strip()
            justification = str(nq.get("justification", "")).strip()
            downloaded_to = str(nq.get("downloaded_to", "")).strip()
            if not url:
                response_lines.append(f"- network_queries[{i}]: (skipped) missing query_or_url")
                continue
            dl_rel = ""
            dl_abs: Path | None = None
            if downloaded_to:
                try:
                    dl_abs = _resolve_under(workspace_root, downloaded_to)
                    dl_rel = logical_project_relpath(dl_abs, workspace_root, project_root)
                    # Require downloads to land under references/ relative to workspace root.
                    dl_rel_ws = _safe_relpath(dl_abs, workspace_root)
                    if not dl_rel_ws.replace("\\", "/").startswith("references/"):
                        response_lines.append(f"- network_queries[{i}]: (denied) downloaded_to must be under references/ (relative to workspace): `{dl_rel_ws}`")
                        dl_abs = None
                        dl_rel = ""
                except Exception as e:
                    response_lines.append(f"- network_queries[{i}]: (error) invalid downloaded_to: {downloaded_to!r}: {e}")
                    dl_abs = None
                    dl_rel = ""
            log_network_query(evidence, url, justification, dl_rel)
            evidence["network_queries"][-1]["request_index"] = i
            if _audit_interceptor is not None:
                _tc = _audit_interceptor.record("network_fetch", url, dl_rel)
                _nq_items = evidence.get("network_queries", [])
                if _nq_items and isinstance(_nq_items[-1], dict):
                    _nq_items[-1]["tc_id"] = _tc
            if dl_abs is None:
                response_lines.append(f"- network_queries[{i}]: logged only (no download): {url}")
                continue
            code_dl, out_dl = _curl_download(url, dl_abs)
            if code_dl != 0:
                response_lines.append(f"- network_queries[{i}]: (download failed) {url} -> `{dl_rel}`")
                response_lines.append("```text")
                response_lines.append(_format_snippet(out_dl, 2000).rstrip())
                response_lines.append("```")
                continue
            try:
                synced_dl = sync_workspace_path(dl_abs, workspace_root, project_root)
                h = sha256_file(synced_dl)
                size = synced_dl.stat().st_size
                log_fetched_source(evidence, url, dl_rel, h, size)
                response_lines.append(f"- network_queries[{i}]: downloaded {url} -> `{dl_rel}` (sha256={h}, bytes={size})")
            except Exception as e:
                response_lines.append(f"- network_queries[{i}]: downloaded, but failed to hash/stat: {e}")
        response_lines.append("")

    # Execute commands.
    if cmds_req:
        response_lines.append("## Commands Run")
        for i, cr in enumerate(cmds_req):
            cmd = str(cr.get("command", "")).strip()
            cwd_s = str(cr.get("cwd", ".")).strip() or "."
            purpose = str(cr.get("purpose", "")).strip()
            timeout = cr.get("timeout_secs", args.request_timeout_secs)
            try:
                timeout_i = int(timeout)
            except Exception:
                timeout_i = args.request_timeout_secs
            expected = cr.get("expected_outputs", [])
            if expected is None:
                expected = []
            if not isinstance(expected, list) or not all(isinstance(x, str) for x in expected):
                expected = []
            if not cmd:
                response_lines.append(f"- commands_run[{i}]: (skipped) missing command")
                continue
            ok, why, cmd_parts = _allowed_command(cmd)
            if not ok:
                response_lines.append(f"- commands_run[{i}]: (denied) {why}: `{cmd}`")
                continue
            # Pre-execution: deny any part (including the executable itself) containing path traversal ('..').
            # Catches traversal in ./-prefixed executables (e.g. ./../member_b/script.sh)
            # and in quoted args (e.g. python3 -c "open('../member_b/...')").
            _traversal_arg = next(
                (a for a in cmd_parts if _ARG_TRAVERSAL_RE.search(a.replace("\\", "/"))),
                None,
            )
            if _traversal_arg is not None:
                response_lines.append(
                    f"- commands_run[{i}]: (denied) arg contains path traversal: {_traversal_arg!r}"
                )
                continue
            # Pre-execution: deny any argument that contains a reference to run_dir
            # that is NOT under the member's workspace.  This covers:
            #   1. Standalone path args:  cat /…/logs/member_b/attempt.log
            #   2. Exact run_dir arg:     ls /…/team/runs/<tag>
            #   3. Embedded path strings: python3 -c "p='/.../tag'; open(p+'/member_b/…')"
            # Strategy: strip all workspace-safe substrings (with AND without trailing
            # slash to handle exact workspace_root args), then check whether run_dir
            # still appears anywhere in what remains.
            _proj_str = str(project_root).rstrip("/")
            _rdir_str = str(run_dir).rstrip("/")
            _ws_str = str(workspace_root).rstrip("/")
            _ws_prefix = _ws_str + "/"

            def _arg_escapes_workspace(a: str) -> bool:
                n = a.replace("\\", "/")
                # Remove workspace-safe occurrences (trailing-slash and exact-root forms).
                cleaned = n.replace(_ws_prefix, "").replace(_ws_str, "")
                return _proj_str in cleaned or _rdir_str in cleaned

            _abs_escape_arg = next((a for a in cmd_parts[1:] if _arg_escapes_workspace(a)), None)
            if _abs_escape_arg is not None:
                response_lines.append(
                    f"- commands_run[{i}]: (denied) argument references run_dir outside workspace: {_abs_escape_arg!r}"
                )
                continue
            if any(_is_forbidden_path(member_id, safe_tag, part) for part in [*cmd_parts, cwd_s]):
                response_lines.append(f"- commands_run[{i}]: (denied) executor payload outside own output prefix")
                continue
            try:
                cwd_abs = _resolve_under(workspace_root, cwd_s)
            except Exception as e:
                response_lines.append(f"- commands_run[{i}]: (error) invalid cwd {cwd_s!r}: {e}")
                continue

            command_inputs = []
            direct_inputs = []
            for token in cmd_parts:
                candidate = (cwd_abs / token).resolve()
                try:
                    local_file = candidate.is_file() and candidate.is_relative_to(workspace_root)
                except OSError:
                    # A literal command value (for example full generated-source
                    # bytes) is not a filename. Preserve it in the original argv.
                    local_file = False
                if local_file:
                    direct_inputs.append(candidate)
            try:
                declared = cr.get("input_files", [])
                if not isinstance(declared, list) or not all(isinstance(x, str) for x in declared):
                    raise ValueError("input_files must be a complete list of path strings")
                for value in declared:
                    candidate = (cwd_abs / value).resolve()
                    if not candidate.is_relative_to(workspace_root) or not candidate.is_file():
                        raise ValueError("declared runtime input is missing or outside workspace")
                    direct_inputs.append(candidate)
                complete_inputs = local_source_closure(direct_inputs, workspace_root, cwd=cwd_abs)
            except (OSError, ValueError, SyntaxError, UnicodeError) as error:
                response_lines.append(f"- commands_run[{i}]: (unavailable) complete input closure: {error}")
                continue
            for j, candidate in enumerate(complete_inputs):
                data = candidate.read_bytes()
                frozen = originals / f"cmd_{i}_input_{j}.txt"
                frozen.write_bytes(data)
                log_output_produced(evidence, _safe_relpath(frozen, project_root), sha256_bytes(data), "complete original proxy command input")
                command_inputs.append({"path": logical_project_relpath(candidate, workspace_root, project_root),
                    "sha256": sha256_bytes(data), "raw_input_ref": artifact_ref(frozen, project_root)})
                runtime_capture_observation._member_files(episode, f"command_input[{i},{j}]", [frozen, candidate])
            out_log = member_run_dir / f"cmd_{i}.log"
            try:
                exit_code, out_bytes = _run_shell(cmd_parts, cwd=cwd_abs, timeout=timeout_i, episode=episode, operation_index=i)
            except subprocess.TimeoutExpired:
                exit_code = 124
                out_bytes = b"TIMEOUT\n"
            out_log.parent.mkdir(parents=True, exist_ok=True)
            out_log.write_bytes(out_bytes)
            runtime_capture_observation._member_files(episode, f"command_output[{i}]", [out_log])
            out_hash = sha256_file(out_log)
            # Only scientific outputs belong to the workspace. The parent also
            # contains immutable producer episodes in the canonical layout.
            member_artifacts_ws = workspace_root / "artifacts" / "runs" / safe_tag / "research_team" / member_id / "independent"
            if member_artifacts_ws.exists() and workspace_root != project_root:
                sync_workspace_path(
                    member_artifacts_ws,
                    workspace_root,
                    project_root,
                    replace_tree=False,
                )
            log_command_run(
                evidence,
                cmd,
                _safe_relpath(cwd_abs, workspace_root),
                exit_code,
                out_hash,
                _safe_relpath(out_log, project_root),
            )
            evidence["commands_run"][-1].update(request_index=i, requested_cwd=cwd_s, input_files=command_inputs)
            if _audit_interceptor is not None:
                _tc = _audit_interceptor.record("command_run", cmd, out_bytes.decode("utf-8", errors="replace"))
                _cr_items = evidence.get("commands_run", [])
                if _cr_items and isinstance(_cr_items[-1], dict):
                    _cr_items[-1]["tc_id"] = _tc

            response_lines.append(f"### commands_run[{i}] exit={exit_code}")
            if purpose:
                response_lines.append(f"- Purpose: {purpose}")
            response_lines.append(f"- Command: `{cmd}`")
            response_lines.append(f"- CWD: `{_safe_relpath(cwd_abs, workspace_root)}`")
            response_lines.append(f"- Output log: `{_safe_relpath(out_log, project_root)}` (sha256={out_hash})")
            response_lines.append("")
            response_lines.append("```text")
            try:
                visible_output = _format_snippet(out_bytes.decode('utf-8', errors='replace'), args.max_cmd_output_chars)
            except ValueError as error:
                evidence["original_transport"].setdefault("pending_operations", []).append({"operation": "commands_run", "request_index": i, "status": "unavailable", "reason": str(error)})
                visible_output = "Complete command output unavailable within configured visibility budget; original bytes retained in the output log."
            response_lines.append(visible_output.rstrip())
            response_lines.append("```")
            if expected:
                response_lines.append("")
                response_lines.append("Expected outputs:")
                for p_s in expected:
                    try:
                        p_abs = _resolve_under(workspace_root, p_s)
                        rel = logical_project_relpath(p_abs, workspace_root, project_root)
                        if not _output_path_allowed(member_id, safe_tag, rel):
                            response_lines.append(
                                f"- (denied) `{rel}` must stay under "
                                f"`artifacts/runs/{safe_tag}/research_team/{member_id}/` or `references/`"
                            )
                            continue
                        if rel.startswith("references/") and p_abs.exists():
                            sync_workspace_path(p_abs, workspace_root, project_root)
                        project_p = project_path_from_workspace(p_abs, workspace_root, project_root)
                        if not project_p.exists():
                            response_lines.append(f"- (missing) `{rel}`")
                            continue
                        h = sha256_file(project_p)
                        log_output_produced(evidence, rel, h, "expected output from requested command")
                        response_lines.append(f"- `{rel}` (sha256={h})")
                    except Exception as e:
                        response_lines.append(f"- (error) {p_s!r}: {e}")
            response_lines.append("")
        response_lines.append("")

    response_path = member_run_dir / "full_access_results.md"
    _write_text(response_path, "\n".join(response_lines).rstrip() + "\n")
    log_output_produced(evidence, _safe_relpath(response_path, project_root), sha256_file(response_path), "full-access proxy results")

    evidence["original_transport"]["proxy_input"] = artifact_ref(response_path, project_root)
    runtime_capture_observation._member_files(episode, "proxy_results", [response_path])

    omitted = []
    for name, requested, recorded in (("files_written", writes_req, evidence["original_transport"].get("construction_refs", [])), ("files_read", files_req, evidence["files_read"]), ("commands_run", cmds_req, evidence["commands_run"]), ("network_queries", net_req, evidence["network_queries"])):
        done = {item.get("request_index") for item in recorded}
        omitted.extend({"operation":name,"request_index":i,"status":"unavailable","reason":"requested operation was not completed"} for i in range(len(requested)) if i not in done)
    evidence["original_transport"].setdefault("pending_operations", []).extend(omitted)
    if evidence["original_transport"]["pending_operations"]:
        save_evidence(out_evidence, evidence)
        print("ERROR: requested proxy operation unavailable; member episode not admissible", file=sys.stderr)
        return 2

    # Final report prompt.
    final_user_prompt = (
        "MODE: FINAL_REPORT\n"
        f"Member: {member_id}\n"
        f"Tag: {tag}\n"
        "\n"
        "You must write your final report using the standard member report format.\n"
        "You may ONLY rely on: (a) the team packet, (b) the proxy results below.\n"
        "Do not claim to have executed tools directly; instead cite evidence by referencing the proxy items\n"
        "as files_read[i], commands_run[i], network_queries[i], outputs_produced[i].\n"
        "\n"
        "If you performed cross-paper / cross-module convention mapping, include a JSON block:\n"
        "```json\n"
        "{\"convention_mappings\": [ {\"source_anchors\": [\"path:line\"], \"explicit_relation\": \"...\", \"sanity_check\": \"...\"} ]}\n"
        "```\n"
        "\n"
        "Team packet follows.\n"
        "----\n"
    ) + packet_txt + "\n\n----\n\nProxy results:\n\n" + _read_text(response_path)

    final_prompt_path = member_run_dir / f"{safe_tag}_final_prompt.txt"
    _build_prompt_for_runner(args.runner_kind, system, final_user_prompt, final_prompt_path)
    # Temporarily restore secret env vars so the final runner call can authenticate.
    os.environ.update(_saved_secrets)
    final_invocation: dict[str, Any] = {}
    original_final_report = member_run_dir / "final_original_report.md"
    code, _ = _run_runner_once(
        invocation=final_invocation,
        episode=episode,
        stage="final",
        runner_kind=args.runner_kind,
        runner=runner,
        system=system,
        prompt=final_prompt_path,
        out=original_final_report,
        model=args.model,
        tools=args.tools,
        output_format=args.output_format,
        api_base_url=args.api_base_url,
        api_key_env=args.api_key_env,
        reasoning_effort=args.reasoning_effort,
    )
    record_original_stage(evidence, "final", final_invocation, system, final_prompt_path, original_final_report, project_root)
    save_evidence(out_evidence, evidence)
    # Pop secrets again — final AI call is done.
    for _k in list(_saved_secrets):
        os.environ.pop(_k, None)
    if code != 0:
        print(f"ERROR: runner failed in final stage (exit {code})", file=sys.stderr)
        return 2

    out_report.parent.mkdir(parents=True, exist_ok=True)
    out_report.write_bytes(original_final_report.read_bytes())
    log_output_produced(evidence, _safe_relpath(original_final_report, project_root), sha256_file(original_final_report), "member report")
    if out_report.is_file():
        log_output_produced(evidence, _safe_relpath(out_report, project_root), sha256_file(out_report), "member report")
        # Convention mappings are optional; attach if present.
        for m in _extract_convention_mappings(_read_text(out_report)):
            log_convention_mapping(evidence, m)

    finalize_member_evidence(evidence)
    save_evidence(out_evidence, evidence)

    issues = validate_member_evidence_schema(load_evidence(out_evidence))
    if any(x.level == "ERROR" for x in issues):
        print("ERROR: wrote invalid evidence.json (full_access)", file=sys.stderr)
        for it in issues:
            print(f"{it.level}: {it.message}", file=sys.stderr)
        return 2

    observation_path = member_run_dir / "runtime_member_episode.json"
    closure = [(project_root / item["path"]).resolve() for item in evidence.get("outputs_produced", [])]
    try:
        runtime_capture_observation._finish_member_episode(episode, evidence, observation_path, closure)
    except (ValueError, OSError) as error:
        print(f"UNAVAILABLE: member producer observation: {error}", file=sys.stderr)
        return 2
    evidence["original_transport"]["runtime_observation"] = artifact_ref(observation_path, project_root)
    save_evidence(out_evidence, evidence)
    save_evidence(member_run_dir / "evidence_original.json", evidence)

    # Also hash the evidence file itself for provenance.
    _ = sha256_file(out_evidence)

    return 0


